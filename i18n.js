// Translations for the parent outreach site.
// The language list and native-language labels follow the picker used on
// workshops.nuevofoundation.org. Languages are added here only once a
// reviewed translation exists, so the picker never offers a broken language.

export const defaultLanguage = "en";

export const languages = Object.freeze([
  { code: "en", label: "English", htmlLang: "en" },
  { code: "es", label: "Español", htmlLang: "es" },
  { code: "fr", label: "Français", htmlLang: "fr" },
  { code: "pt-br", label: "Português Brasileiro", htmlLang: "pt-BR" },
]);

export const languageCodes = Object.freeze(languages.map((language) => language.code));

export function resolveLanguage(requested, preferred = []) {
  const candidates = [requested, ...preferred].filter((value) => typeof value === "string" && value);
  for (const candidate of candidates) {
    const normalized = candidate.trim().toLowerCase();
    if (languageCodes.includes(normalized)) return normalized;
    // Accept regional variants such as es-MX or pt-PT by matching the base tag.
    const base = normalized.split("-")[0];
    const match = languageCodes.find((code) => code === base || code.split("-")[0] === base);
    if (match) return match;
  }
  return defaultLanguage;
}

function joiner(separator, conjunction, oxford = false) {
  return (items) => {
    if (items.length === 0) return "";
    if (items.length === 1) return items[0];
    if (items.length === 2) return items.join(` ${conjunction} `);
    return `${items.slice(0, -1).join(separator)}${oxford ? separator : " "}${conjunction} ${items.at(-1)}`;
  };
}

